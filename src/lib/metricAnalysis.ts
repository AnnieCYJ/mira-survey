/**
 * metricAnalysis —— 基础指标卡（心率/血氧/HRV/体温/皮电/交感…）下方的一段 AI 分析文案生成
 * ---------------------------------------------------------------------------
 * 设计口径（对齐 Mira 品牌铁律：只描述、不诊断、不评分）：
 *   · 不依赖临床阈值硬判「正常/异常」——避免无依据结论；
 *   · 始终把读数放进「荷尔蒙节律 / 昼夜节律 / 生理周期节律」语境里解读；
 *   · 无数据时给温和引导，不画空结论。
 * 各指标逐条定制，周期/昼夜/激素语境通用，读起来自然、不机械。
 */

import { showCycleContent } from '../data/cycleScope';

type M = { key: string; name: string; unit?: string };

/** ★ 2026-11-10（用户）：文案里的瞬时读数与卡片大数值必须同口径，一律整数
 *  （心率变异性「当前 59.5ms」→「当前 60ms」）。
 *  全 App 唯一允许 1 位小数的是「身体年龄」，不经过本函数。 */
function lead(m: M, v: number | null): string {
  if (v == null || !Number.isFinite(v)) return '';
  const u = m.unit ?? '';
  return `当前 ${String(Math.round(v))}${u}，`;
}

/**
 * ★ 2026-11-13（用户）：戒指数据是按指标陆陆续续回来的——心率先到、HRV/血氧还要再等一段，
 *   这段窗口里卡片大数值是「—」，底部文案却写「今日暂未读到数据」，看起来像坏了/没连上。
 *   `loading=true` 时在文案中间插入一句「正在加载中」，明确告诉用户数据还在路上。
 *   调用方（useRingDataLoading）有硬超时，超时后自动回落到原来的「暂未读到数据」，
 *   绝不长时间挂着「正在加载中」误导用户。
 */
export function buildMetricAnalysis(m: M, value: number | null, loading = false): string {
  // ★ 2026-11-14：男性用户的指标解读不出现「生理周期相位 / 黄体期 / 排卵后」等女性周期表述。
  const cycleOn = showCycleContent();
  if (value == null) {
    const tail = cycleOn
      ? '并给出参考你荷尔蒙节律、昼夜节律与生理周期相位的分析。'
      : '并给出参考你昼夜节律与近期趋势的分析。';
    if (loading) {
      return `${m.name}今日暂未读到数据。正在加载中，戒指数据会分批回来，先到的指标先显示。连接戒指并佩戴一会儿后，这里会显示读数，${tail}`;
    }
    return `${m.name}今日暂未读到数据。连接戒指并佩戴一会儿后，这里会显示读数，${tail}`;
  }
  if (!cycleOn) {
    // 男性中性版：保留指标本身的生理解释，去掉全部周期绑定话术
    switch (m.key) {
      case 'hr':
        return `${lead(m, value)}心率反映自主神经张力与循环负荷，会随昼夜节律、活动与压力自然波动——夜间静息、运动后偏高都属正常变化。把它和近期睡眠、压力趋势放在一起看，是日常状态最敏感的窗口之一。`;
      case 'hrv':
        return `${lead(m, value)}心率变异性体现自主神经的恢复与调节能力，受睡眠、压力与作息共同影响。偏低常对应疲劳或高压，偏高提示恢复较好；把它放进你的昼夜节律里看，比单看一个数字更有意义。`;
      case 'temp':
      case 'tempCore':
        return `${lead(m, value)}体温受活动、环境温度与测量时间影响，昼夜之间有自然起伏。单日读数波动多为正常，建议结合多日趋势判断。`;
      case 'eda':
        return `${lead(m, value)}皮肤含水量是与皮电相关的相对读数，会受饮水量、环境湿度和出汗影响。偏低时先想想是不是喝水少或环境干燥，结合作息和近期趋势看，不必被单次数值牵着走。`;
      case 'rr':
        return `${lead(m, value)}呼吸率与自主神经、代谢状态相关，睡眠中平稳放缓是恢复良好的表现，也受昼夜节律调制。`;
      case 'stress':
        return `${lead(m, value)}压力是戒指综合生理信号给出的紧张度读数。短期升高常见于工作紧张、运动或熬夜，回落后会自然下降；连着几天都偏高，说明身体一直处在紧绷状态，睡眠和恢复往往也会受影响，这时候优先看睡眠和休息够不够。`;
      case 'fatigue':
        return `${lead(m, value)}疲劳度结合睡眠与活动量评估身体消耗。睡得少、连续高强度活动后升高是正常反应，休息一晚多会回落；若持续偏高、白天注意力下降，先回头看这几天的睡眠时长和活动强度。`;
      case 'emotion':
        return `${lead(m, value)}情绪是设备落在 −10 到 10 刻度上的活动状态，正值偏积极、负值偏低落。单次读数受当下情境影响大，看一段时间主要落在哪一段，比盯着某一刻更能反映近期状态。`;
      case 'skin':
        return `${lead(m, value)}皮肤含水量是与皮电相关的相对读数，会受饮水量、环境湿度和出汗影响。偏低时先想想是不是喝水少或环境干燥，结合作息和近期趋势看，不必被单次数值牵着走。`;
      default:
        return `${lead(m, value)}${m.name}反映身体的一项基础信号，会随昼夜节律、睡眠与压力自然波动。保持规律睡眠与稳定情绪，读数通常落在平稳区间。`;
    }
  }
  switch (m.key) {
    case 'hr':
      return `${lead(m, value)}心率反映自主神经张力与循环负荷，会随你的生理周期相位与昼夜节律自然波动——夜间静息、黄体期及运动后偏高都属正常变化。把它和近期睡眠、压力趋势放在一起看，是日常状态最敏感的窗口之一。`;
    case 'hrv':
      return `${lead(m, value)}心率变异性体现自主神经的恢复与调节能力，受睡眠、压力与周期激素共同影响。偏低常对应疲劳或高压，偏高提示恢复较好；把它放进你的昼夜节律里看，比单看一个数字更有意义。`;
    case 'spo2':
      return `${lead(m, value)}血氧饱和度反映血液携氧水平，夜间轻微下降、运动时波动都属生理范围。持续低于正常区间才需留意，可结合睡眠呼吸一起看。`;
    case 'temp':
    case 'tempCore':
      return `${lead(m, value)}基础体温随生理周期相位变化明显（排卵后升高），是周期节律最直观的信号。单日读数受活动与测量时间影响，建议结合多日趋势判断。`;
      case 'eda':
        return `${lead(m, value)}皮肤含水量是与皮电相关的相对读数，会受饮水量、环境湿度和出汗影响，也随周期激素波动。偏低时先想想是不是喝水少或环境干燥，结合作息和近期趋势看，不必被单次数值牵着走。`;
    case 'sns':
      return `${lead(m, value)}交感神经活跃度代表唤醒与应激水平，白天高、夜间低是健康昼夜节律的体现。若夜间持续偏高，常提示压力或作息不规律，值得关注。`;
    case 'rr':
      return `${lead(m, value)}呼吸率与自主神经、代谢状态相关，睡眠中平稳放缓是恢复良好的表现，同样受周期激素与昼夜节律调制。`;
    case 'stress':
      return `${lead(m, value)}压力是戒指综合生理信号给出的紧张度读数。短期升高常见于工作紧张、运动或熬夜，经前与黄体期也更容易感到紧绷；连着几天都偏高，睡眠和恢复往往跟着变差，这时候优先看休息够不够。`;
    case 'fatigue':
      return `${lead(m, value)}疲劳度结合睡眠与活动量评估身体消耗。睡得少、连续高强度活动后升高是正常反应，黄体期代谢上升时也更容易累；休息一晚多会回落，若持续偏高就回头看这几天的睡眠和活动强度。`;
    case 'emotion':
      return `${lead(m, value)}情绪是设备落在 −10 到 10 刻度上的活动状态，正值偏积极、负值偏低落。经前和黄体期情绪更容易起伏，属常见波动；看一段时间主要落在哪一段，比盯某一刻更能反映近期状态。`;
    case 'skin':
      return `${lead(m, value)}皮肤含水量是与皮电相关的相对读数，会受饮水量、环境湿度和出汗影响，也随周期激素波动。偏低时先想想是不是喝水少或环境干燥，结合作息和近期趋势看，不必被单次数值牵着走。`;
    default:
      return `${lead(m, value)}${m.name}反映身体的一项基础信号，会随你的荷尔蒙节律、昼夜节律与生理周期相位自然波动。保持规律睡眠与稳定情绪，读数通常落在平稳区间。`;
  }
}
