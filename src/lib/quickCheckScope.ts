/**
 * 一键体检「本次依据」口径（★ 2026-11-13 用户拍板）
 * ---------------------------------------------------------------------------
 * 用户口径：
 *   · 首次进入、还没什么数据 → 报告只展示「这次现场测得的 + 由这次读数算出的」；
 *   · 已经戴了一段时间、中途又测一次 → 现场测量 + 最近已同步的数据一起展示。
 *
 * 实现上不需要 `if (isFirstTime)` 两套分支：每一项本来就有「没读数就不展示」守卫，
 * 首次时「今日已同步」与「最近记录推算」两层天然为空，报告自动收窄成前两层。
 * 本模块负责给「最近」划出边界，并生成报告里那一句给用户看的依据说明。
 *
 * 「最近」的边界（防止旧值冒充今天）：
 *   · 单点读数（心率 / 血氧 / 血压 / 睡眠 / 体温…）：只认**本次现场**或**今天已同步**；
 *     绝不拿几天前「最后一次」的读数顶替今天的数值。
 *   · 跨天的是「节律」类**趋势结论**（近 7 / 14 天记录）：它是推算、不是读数，
 *     报告里写明「基于最近 N 天记录」。
 *   · 今日状态 / 身心压力：每次用本次现场值重算，不沿用上一次的分数。
 *
 * 纯 TS、零依赖，可在 Node 下独立编译做断言（见 scripts/ble-release-gate.mjs）。
 */

/** 节律类趋势结论至少需要几天的记录才会出现（与节律组近 7 天睡眠规律性一致）。 */
export const RHYTHM_MIN_DAYS = 7;

export type ScopeStage = 'first' | 'building' | 'ongoing';

export interface QuickCheckScope {
  /** 本次 35 秒窗口内新回流的现场读数（心率 / 血氧） */
  hasLive: boolean;
  /** 今天已同步、但不是这次现场测得的读数 */
  hasToday: boolean;
  /** 最近有记录的天数（来自 dailyHistory 的逐日序列） */
  historyDays: number;
}

/** 首次 / 逐步积累 / 已连续佩戴：只用于选择说明文案，不影响数据组装。 */
export function classifyScope(s: QuickCheckScope): ScopeStage {
  if (s.historyDays >= RHYTHM_MIN_DAYS) return 'ongoing';
  if (s.hasToday || s.historyDays > 0) return 'building';
  return 'first';
}

/** 报告首组的依据说明：让用户知道这一份报告里的数字各来自哪里。 */
export function scopeNote(s: QuickCheckScope): string {
  // 这次没测到现场值（比如戒指没戴稳）：不能还说「以现场测量为准」。
  // 报告里只剩今天已同步的读数，状态分同样要用这些读数重算，不沿用上次分数。
  if (!s.hasLive) {
    return '这次没有现场读到新值，报告里的读数取今天已同步的数据；今日状态与身心压力用这些读数重新算出，不沿用上一次的分数。'
      + (classifyScope(s) === 'ongoing' ? '节律部分仍来自最近 7–14 天记录，是趋势推算。' : '');
  }
  switch (classifyScope(s)) {
    case 'first':
      return '这次只展示刚刚现场测得的心率、血氧，以及用它们算出的今日状态与身心压力；佩戴并同步后，报告会逐步加入更多读数。';
    case 'building':
      return '这次以刚刚现场测得的读数为准，一起列出今天已同步的数据；今日状态与身心压力用这次的读数重新算出，不沿用上一次的分数。节律结论需要连续几天的记录才会出现。';
    case 'ongoing':
      return '这次以现场测量为准，结合今天已同步的读数重新算出今日状态与身心压力；节律部分来自最近 7–14 天记录，是趋势推算，不是这次现场测得的数值。';
  }
}
