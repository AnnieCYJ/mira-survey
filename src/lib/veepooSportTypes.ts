/** 固件 type → 强度系数 MET（未列出回落 DEFAULT_MET） */
export function sportMetOf(type?: number): number {
  if (type == null) return DEFAULT_MET;
  return MET[type] ?? DEFAULT_MET;
}

/**
 * 还原一段运动的类型展示名。
 * 优先用原生给出的名字；原生没给、或给的是兜底「未知(N)」时，用全量表按 type 补全。
 */
export function resolveSportName(type?: number, nativeName?: string): string {
  const raw = (nativeName ?? '').trim();
  const nativeIsFallback = raw === '' || raw.startsWith('未知') || raw === 'Unknown';
  if (!nativeIsFallback) return raw;
  if (type == null) return raw !== '' ? raw : '运动';
  return VEEPOO_SPORT_NAMES[type] ?? `运动 ${type}`;
}

/** 固件 type → 估算消耗 kcal（分钟 × MET × 体重 ÷ 60）；仅用于固件 totalCal 缺失时兜底。 */
export function estimateSportKcal(type: number | undefined, minutes: number, weightKg = 55): number {
  return Math.round((sportMetOf(type) * Math.max(0, minutes) * weightKg) / 60);
}
