/** 世界书注入：扫描文本命中的 key，拼接命中的 content，受 token budget 限制（对应 Swift injectCompanion） */
export function buildCompanionInjection(recentText: string, budget = 900): string {
  const hits: string[] = [];
  let used = 0;
  for (const e of WORLD_BOOK) {
    if (e.keys.some((k) => recentText.includes(k))) {
      if (used + e.content.length > budget) continue;
      hits.push(e.content);
      used += e.content.length;
    }
  }
  return hits.length ? `【健康陪伴话术锚点（仅作语气/知识参考，不要照搬原句）】\n` + hits.join('\n\n') : '';
}

/** 组装 system prompt：基础人设 + 按近期内容触发的世界书锚点 */
export function buildSystemPrompt(recentText: string): string {
  const companion = buildCompanionInjection(recentText);
  return companion ? `${CHARACTER.system_prompt}\n\n${companion}` : CHARACTER.system_prompt;
}
